    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {                                         
        // TODO add your handling code:
        
        String forest = cmbForest.getSelectedItem().toString();
        String convex = cmbConvex.getSelectedItem().toString();
        String gills = cmbGills.getSelectedItem().toString();
        String ring = cmbRing.getSelectedItem().toString();

// Question 1 is always required
if (forest.equals("Select...")) {
    lblMushroom.setText("Please answer: Does it grow in a forest?");
    return;
}

String mushroom;

if (forest.equals("No")) {
    // Branch 1 only requires knowing about the convex cap
    if (convex.equals("Select...")) {
        lblMushroom.setText("Please answer: Does it have a convex cap?");
        return;
    }
    
    if (convex.equals("Yes")) {
        mushroom = "Agaric jaunissant";
    } else {
        mushroom = "Coprin chevelu";
    }

} else {
    // Branch 2 requires knowing about gills first
    if (gills.equals("Select...")) {
        lblMushroom.setText("Please answer: Does it have gills?");
        return;
    }

    if (gills.equals("No")) {
        mushroom = "Cepe de bordeaux";
    } else {
        // Only if it has gills do we require knowing about the ring
        if (ring.equals("Select...")) {
            lblMushroom.setText("Please answer: Does it have a ring?");
            return;
        }
        
        if (ring.equals("Yes")) {
            mushroom = "Amanite tue-mouche";
        } else {
            mushroom = "Pied bleu";
        }
    }
}

lblMushroom.setText("Your mushroom is: " + mushroom);
        
    }                                        

