    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {                                         
        // TODO add your handling code here:
        
        try {
    int startHour = Integer.parseInt(txtStart.getText());
    int endHour = Integer.parseInt(txtEnd.getText());
    int totalCost = 0;

    if (startHour < 0 || endHour > 24 || startHour >= endHour) {
        lblResult.setText("Invalid hours!");
        return;
    }

    for (int h = startHour; h < endHour; h++) {
        if ((h >= 0 && h < 7) || (h >= 21 && h < 24)) {
            totalCost += 500;
        } else if ((h >= 7 && h < 14) || (h >= 19 && h < 21)) {
            totalCost += 1000;
        } else if (h >= 14 && h < 19) {
            totalCost += 1500;
        }
    }
    lblResult.setText("Total Cost = " + totalCost+ "RWF");
} catch (NumberFormatException e) {
    lblResult.setText("Please enter valid numbers!");
}
        
    }                                        

