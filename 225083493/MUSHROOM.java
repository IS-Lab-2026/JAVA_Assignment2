    private void btnidentifyActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnidentifyActionPerformed
        boolean gills = checkgills.isSelected();
    boolean forest = checkforest.isSelected();
    boolean ring = checkring.isSelected();
    boolean cup = checkcup.isSelected();

    String result;

    if (!gills) {
        result = "Cepe de Bordeaux";
    } else if (!forest) {
        // Meadow branch
        if (cup) {
            result = "Agaric Jaunissant";
        } else {
            result = "Coprin Chevelu";
        }
    } else {
        // Forest branch
        if (ring) {
            result = "Amanite Tue-Mouche";
        } else if (cup) {
            result = "Pied Bleu";
        } else {
            result = "Girolle";
        }
    }

    resultField.setText(result);
// TODO add your handling code here:
    }//GEN-LAST:event_btnidentifyActionPerformed

