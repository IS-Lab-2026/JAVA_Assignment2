    private void btncalculateamountActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btncalculateamountActionPerformed
int startTime = Integer.parseInt(txtstart.getText());
    int endTime = Integer.parseInt(txtend.getText());

    int hours = endTime - startTime;

    int rate = 500;

    int total = hours * rate;

    txttotal.setText(
        "Total hours: " + hours +
        "\nRate: " + rate + " RWF" +
        "\nTotal amount: " + total + " RWF"
    );


    }//GEN-LAST:event_btncalculateamountActionPerformed

