    private void btnactionActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnactionActionPerformed

    String result;

    // Check forest question
    if (!rdoforestyes.isSelected() && !rdoforestno.isSelected()) {

        JOptionPane.showMessageDialog(this,
            "Please answer the forest question!");

    }

    // If mushroom does not grow in a forest
    else if (rdoforestno.isSelected()) {

        if (rdoconvexyes.isSelected()) {

            result = "Agaric jaunissant";

            jTextArea1.setText(result);

        }

        else if (rdoconvexno.isSelected()) {

            result = "Coprin chevelu";

            jTextArea1.setText(result);

        }

        else {

            JOptionPane.showMessageDialog(this,
                "Please answer the convex cup question!");

        }

    }

    // If mushroom grows in a forest
    else if (rdoforestyes.isSelected()) {

        // Check convex cup question
        if (!rdoconvexyes.isSelected() && !rdoconvexno.isSelected()) {

            JOptionPane.showMessageDialog(this,
                "Please answer the convex cup question!");

        }

        // Convex cup is Yes
        else if (rdoconvexyes.isSelected()) {

            if (rdoringyes.isSelected()) {

                result = "Amanite tue-mouches";

                jTextArea1.setText(result);

            }

            else if (rdoringno.isSelected()) {

                result = "Pied bleu";

                jTextArea1.setText(result);

            }

            else {

                JOptionPane.showMessageDialog(this,
                    "Please answer the ring question!");

            }

        }

        // Convex cup is No
        else if (rdoconvexno.isSelected()) {

            if (rdogrilsyes.isSelected()) {

                result = "Girolle";

                jTextArea1.setText(result);

            }

            else if (rdogrilsno.isSelected()) {

                result = "Cepe de Bordeaux";

                jTextArea1.setText(result);

            }

            else {

                JOptionPane.showMessageDialog(this,
                    "Please answer the grills question!");

            }

        }

    }


    
   
    }//GEN-LAST:event_btnactionActionPerformed

