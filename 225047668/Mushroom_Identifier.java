    private void IdentifierbtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_IdentifierbtnActionPerformed

    boolean ring   = Ringcbox.getSelectedItem().toString().equalsIgnoreCase("Yes");
    boolean forest = Forestcbox.getSelectedItem().toString().equalsIgnoreCase("Yes");
    boolean cup    = Cupcbox.getSelectedItem().toString().equalsIgnoreCase("Yes");
    boolean gills  = Gillscbox.getSelectedItem().toString().equalsIgnoreCase("Yes");

    String result;

    if (ring) {
        if (forest) {
            result = "Amanite tue-mouche";
        } else if (cup) {
            result = "Agaric jaunissant";
        } else {
            result = "Coprin chevelu";
        }
    } else {
        if (!gills) {
            result = "Cepe de bordeaux";
        } else if (cup) {
            result = "Pied bleu";
        } else {
            result = "Girolle";
        }
    }

    Resulttxt.setText("Your mushroom is: " + result);

    }//GEN-LAST:event_IdentifierbtnActionPerformed

