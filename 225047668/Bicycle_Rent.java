    private void CalcbtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_CalcbtnActionPerformed
       int start_time_,_end_time;

    try {
        start_time_ = Integer.parseInt(Starttxt.getText().trim());
        _end_time = Integer.parseInt(Endtxt.getText().trim());
    } catch (NumberFormatException e) {
        Resulttxt.setText("Invalid input: whole numbers only.");
        return;
    }

    if (start_time_ < 0 || start_time_ > 23 || _end_time < 1 || _end_time > 24 || start_time_ >= _end_time) {
        Resulttxt.setText("Invalid range: start 0-23, end 1-24, start < end.");
        return;
    }

    int total = 0;
    for (int h = start_time_; h < _end_time; h++) {
        if (h < 7 || h >= 21) {
            total += 500;
        } else if (h < 14 || h >= 19) {
            total += 1000;
        } else {
            total += 1500;
        }
    }

    Resulttxt.setText("Hours: " + (_end_time - start_time_) + " | Total: " + total + " RWF");

    }//GEN-LAST:event_CalcbtnActionPerformed

