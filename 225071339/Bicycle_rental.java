    private void btncalculateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btncalculateActionPerformed

 // TODO add your handling code here:
    try {
                    int startTime = Integer.parseInt(txtstart.getText().trim());
                    int endTime = Integer.parseInt(txtend.getText().trim());
                    int total =0;
        int hours, rate;
        if(startTime<0|| startTime>23){
             txtTotal.setText("invalid");
        }
         else if(endTime<1|| endTime>24){
             
             txtTotal.setText("Invalid end time");}
         else if (startTime>=endTime)
         {
             txtTotal.setText("Invalid input");
                 }
         else{    
               
        hours = endTime - startTime;
                 
         if(startTime>=0 && endTime<7|| startTime>=21 && endTime<24){
        rate = 500;
    }
         
         else if(startTime>=7 && endTime<14||startTime>=19 && endTime<21){
        rate = 1000;
    }
         else {
        rate = 1500;
    }  
    
         total=hours*rate;
         txtTotal.setText( total +"rwf");
                  }
    }
                 catch (NumberFormatException e) {
                    txtTotal.setText("Invalid");
                }
    }//GEN-LAST:event_btncalculateActionPerformed

