    private void BtnActionActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtnActionActionPerformed
        if(RdoyesRing.isSelected()){
            if (RdoyesForest.isSelected()){
                txtmushroom.setText(" Amanite tue-mouche");
            }
            else if(RdonoForest.isSelected()){
                if(RdoyesCup.isSelected()){
                    txtmushroom.setText("Agaric Jaunissant");
                }
                else if(RdonoCup.isSelected()){
                   txtmushroom.setText("Coprin chevelu");
                }
                else{
                    txtmushroom.setText("Invalid input");
                }
            }
            else{
               txtmushroom.setText("Invalid input"); 
            }
        }
        else if(RdonoRing.isSelected()){
            if(RdoyesGills.isSelected()){
                if(RdoyesCup.isSelected()){
                    txtmushroom.setText("Pied bleu");
                }
                else if(RdonoCup.isSelected()){
                   txtmushroom.setText("Girolle"); 
                }
                else{
                  txtmushroom.setText("Invalid input");
                }
        }
            else if(RdonoGills.isSelected()){
                txtmushroom.setText("Cepe de bordeau");
            }
            else{
                txtmushroom.setText("Invalid input");
            }
        }
        else{
          txtmushroom.setText("Invalid input");  
        }
       
                       
    }//GEN-LAST:event_BtnActionActionPerformed

