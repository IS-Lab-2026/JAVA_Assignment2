    private void btnexecuteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnexecuteActionPerformed
       // 1. CHECK IF ALL QUESTIONS ARE ANSWERED

if (!(rbtnringyes.isSelected() || rbtnringno.isSelected())) {
    JOptionPane.showMessageDialog(null, "Please answer: Does your mushroom have a ring?");
    return;
}

if (!(rbtnforestyes.isSelected() || rbtnforestno.isSelected())) {
    JOptionPane.showMessageDialog(null, "Please answer: Does your mushroom grow in a forest?");
    return;
}

if (!(rbtnconvexyes.isSelected() || rbtnconvexno.isSelected())) {
    JOptionPane.showMessageDialog(null, "Please answer: Does your mushroom have a convex cap?");
    return;
}

if (!(rbtngillsyes.isSelected() || rbtngillsno.isSelected())) {
    JOptionPane.showMessageDialog(null, "Please answer: Does your mushroom have gills?");
    return;
}

// 2. GET THE ANSWERS

boolean hasRing = rbtnringyes.isSelected();
boolean inForest = rbtnforestyes.isSelected();
boolean convexCap = rbtnconvexyes.isSelected();
boolean hasGills = rbtngillsyes.isSelected();

// 3. IDENTIFY THE MUSHROOM

String result;

if (hasRing && inForest && convexCap && hasGills) {
    result = "Amanita Mushroom";
} else if (hasRing && !inForest && convexCap && hasGills) {
    result = "Button Mushroom (Champignon)";
} else if (!hasRing && inForest && convexCap && hasGills) {
    result = "Chanterelle Mushroom";
} else if (!hasRing && !inForest && !convexCap && hasGills) {
    result = "Oyster Mushroom";
} else if (hasRing && inForest && !convexCap && !hasGills) {
    result = "Porcini Mushroom";
} else {
    result = "Unknown Mushroom - Not Identified";
}

// 4. SHOW THE RESULT IN THE TEXT FIELD

TxtMushroomName.setText(result); // TODO add your handling code here:
    }//GEN-LAST:event_btnexecuteActionPerformed

