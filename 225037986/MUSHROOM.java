    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
          if (rdoyesconvexcup.isSelected()) {
            if (rdonoforest.isSelected()) {
               txtresults.setText("Agaric jaunissant");
            } else {

                if (Rdoyesring.isSelected()) {
                   txtresults.setText("Amanite tue-mouche");
                } else {
                    txtresults.setText("Pied bleu");
                }
            }

        } else {
            if (Rdonoring.isSelected()) {
               txtresults.setText("Cepe de bordeaux");
            } else {
                if (rdoyesforest.isSelected()) {
                    txtresults.setText("Girolle");
                } else {
                    txtresults.setText("Coprin chevelu");
                }}}
    }//GEN-LAST:event_jButton1ActionPerformed

