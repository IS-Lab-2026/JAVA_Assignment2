    public int calculateRentalCost(int startTime, int endTime) {

    if (startTime < 0 || startTime > 23 ||
        endTime < 1 || endTime > 24 ||
        startTime >= endTime) {

        throw new IllegalArgumentException("Invalid time!");
    }

    int amount = 0;

    for (int hour = startTime; hour < endTime; hour++) {

        if (hour < 7) {
            amount += 500;
        } 
        else if (hour < 14) {
            amount += 1000;
        } 
        else if (hour < 19) {
            amount += 1500;
        } 
        else if (hour < 21) {
            amount += 1000;
        } 
        else {
            amount += 500;
        }
    }

    return amount;
} 
