    private void btnexecuteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnexecuteActionPerformed
        String result;

    if (RadioYes.isSelected()) {
        if (RadioYes2.isSelected()) {
            result = "Amanite tue-mouche";
        } else if (RadioNo2.isSelected()) {
            if (RadioYes3.isSelected()) {
                result = "Agaric Jaunissant";
            } else if (RadioNo3.isSelected()) {
                result = "Coprin chevelu";
            } else {
                result = "Invalid input";
            }
        } else {
            result = "Invalid input";
        }
    } else if (RadioNo.isSelected()) {
        if (RadioYes4.isSelected()) {
            if (RadioYes3.isSelected()) {  // convex radio yes
                result = "Pied bleu";
            } else if (RadioNo3.isSelected()) {
                result = "Girolle";
            } else {
                result = "Invalid input";
            }
        } else if (RadioNo4.isSelected()) {  // Gills Radio
            result = "Cepe de bordeau";
        } else {
            result = "Invalid input";
        }
    } else {
        result = "Invalid input";
    }

    txtResult.setText(result);
        // TODO add your handling code here:
    }//GEN-LAST:event_btnexecuteActionPerformed

