    private void btncalculateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btncalculateActionPerformed
      if (Txtstart.getText().trim().isEmpty() || TxtEnd.getText().trim().isEmpty()) {
                    JOptionPane.showMessageDialog(null, "Please fill both Starttime and Endtime!");
                    TxtTotal.setText("");
                    return;
                }

                try {
                    int start = Integer.parseInt(Txtstart.getText().trim());
                    int end = Integer.parseInt(TxtEnd.getText().trim());

                   
                    if (start < 0 || start > 23) {
                        JOptionPane.showMessageDialog(null, "Starttime must be between 0 and 23!");
                        TxtTotal.setText("");
                        return;
                    }

                   
                    if (end < 1 || end > 24) {
                        JOptionPane.showMessageDialog(null, "Endtime must be between 1 and 24!");
                        TxtTotal.setText("");
                        return;
                    }

                    
                    if (end <= start) {
                        JOptionPane.showMessageDialog(null, "Endtime must be bigger than Starttime!");
                        TxtTotal.setText("");
                        return;
                    }

                   
                    int hours = end - start;
                    double total = hours * 500;

                    TxtTotal.setText(total + " RWF (" + hours + " hours)");

                } catch (NumberFormatException e) {
                   
                    JOptionPane.showMessageDialog(null, "Please enter numbers only! No letters.");
                    TxtTotal.setText("");
                }   // TODO add your handling code here:
    }//GEN-LAST:event_btncalculateActionPerformed

