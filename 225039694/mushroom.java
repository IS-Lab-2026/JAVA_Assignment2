    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
if (!jRadioButton1.isSelected() && !jRadioButton2.isSelected()) {
    jTextArea1.setText("Please answer whether the mushroom has a convex cup.");
    return;
}

String mushroom;

if (jRadioButton1.isSelected()) { // Convex cup = yes
    if (!jRadioButton3.isSelected() && !jRadioButton4.isSelected()) {
        jTextArea1.setText("Please answer whether the mushroom has a ring.");
        return;
    }

    if (jRadioButton4.isSelected()) { // Ring = no
        mushroom = "Pied bleu";
    } else { // Ring = yes
        if (!jRadioButton5.isSelected() && !jRadioButton6.isSelected()) {
            jTextArea1.setText("Please answer whether the mushroom grows in a forest.");
            return;
        }
        mushroom = jRadioButton5.isSelected() ? "Amanite tue-mouches" : "Agaric jaunissant";
    }
} else { // Convex cup = no
    if (!jRadioButton3.isSelected() && !jRadioButton4.isSelected()) {
        jTextArea1.setText("Please answer whether the mushroom has a ring.");
        return;
    }

    if (jRadioButton3.isSelected()) { // Ring = yes
        mushroom = "Coprin chevelu";
    } else { // Ring = no
        if (!jRadioButton7.isSelected() && !jRadioButton8.isSelected()) {
            jTextArea1.setText("Please answer whether the mushroom has gills.");
            return;
        }
        mushroom = jRadioButton7.isSelected() ? "Girolle" : "Cepe de bordeaux";
    }
}

jTextArea1.setText("Your mushroom is: " + mushroom);        // TODO add your handling code here:
    }//GEN-LAST:event_jButton1ActionPerformed

