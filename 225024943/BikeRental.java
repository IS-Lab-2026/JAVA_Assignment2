    private void calcRental(){
        try {
        int x = Integer.parseInt(pickf.getText().trim());
        int y = Integer.parseInt(endf.getText().trim()); // update "endf" if your ending field has a different variable name

        if (x < 0 || x > 23 || y < 1 || y > 24 || x >= y) { // note: if pickup == ending, rental is 0 hours, so x >= y catches invalid/empty duration
            resultsfield.setText("Invalid input! Try again."); // update "results" if your result label has a different variable name
            return;
        }

        int cost = 0;

        for (int hr = x; hr < y; hr++) {
            if ((hr >= 0 && hr < 7) || (hr >= 21 && hr < 24)) {
                cost += 500;
            } else if ((hr >= 7 && hr < 14) || (hr >= 19 && hr < 21)) {
                cost += 1000;
            } else if (hr >= 14 && hr < 19) {
                cost += 1500;
            }
        }

        resultsfield.setText("Your total cost is " + cost);

    } catch (NumberFormatException e) {
        resultsfield.setText("Invalid input! Try again.");
    }
    }
    
