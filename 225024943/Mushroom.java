    private enum QuestionStep {
    NONE,
    RING,
    FOREST_WHEN_RING_YES,
    CONVEX_WHEN_RING_YES_NO_FOREST,
    GILLS_WHEN_RING_NO,
    CONVEX_WHEN_RING_NO_GILLS_YES,
    FINISHED
}

private QuestionStep currentStep = QuestionStep.NONE;
private void showStartScreen() {
    currentStep = QuestionStep.NONE;

    questionLabel.setText("");
    questionLabel.setVisible(false);

    startBtn.setVisible(true);
    backBtn.setVisible(true);
    backBtn.setEnabled(true);

    restartBtn.setVisible(false);
    yesBtn.setVisible(false);
    noBtn.setVisible(false);
}

private void startQuiz() {
    startBtn.setVisible(false);
    backBtn.setVisible(false);
    questionLabel.setVisible(true);
    restartBtn.setVisible(true);
    yesBtn.setVisible(true);
    noBtn.setVisible(true);

    goToStep(QuestionStep.RING);
}

private void goToStep(QuestionStep nextStep) {
    currentStep = nextStep;
    updateQuestionText();
}

private void showMushroomResult(String mushroomName) {
    currentStep = QuestionStep.FINISHED;
    questionLabel.setText("You chose " + mushroomName);
    yesBtn.setEnabled(false);
    noBtn.setEnabled(false);
}

private void updateQuestionText() {
    boolean activeQuestion = (currentStep != QuestionStep.NONE && currentStep != QuestionStep.FINISHED);
    yesBtn.setEnabled(activeQuestion);
    noBtn.setEnabled(activeQuestion);

    switch (currentStep) {
        case RING -> questionLabel.setText("Does your mushroom have a ring?");
        case FOREST_WHEN_RING_YES -> questionLabel.setText("Does it grow in a forest?");
        case CONVEX_WHEN_RING_YES_NO_FOREST -> questionLabel.setText("Does it have convex cup?");
        case GILLS_WHEN_RING_NO -> questionLabel.setText("Does it have Gills?");
        case CONVEX_WHEN_RING_NO_GILLS_YES -> questionLabel.setText("Does it have convex cup?");
        case NONE, FINISHED -> { }
    }
}

private void handleYes() {
    switch (currentStep) {
        case RING -> goToStep(QuestionStep.FOREST_WHEN_RING_YES);
        case FOREST_WHEN_RING_YES -> showMushroomResult("Amanite tue-mouche");
        case CONVEX_WHEN_RING_YES_NO_FOREST -> showMushroomResult("Agaric jaunissant");
        case GILLS_WHEN_RING_NO -> goToStep(QuestionStep.CONVEX_WHEN_RING_NO_GILLS_YES);
        case CONVEX_WHEN_RING_NO_GILLS_YES -> showMushroomResult("Pied bleu");
        case NONE, FINISHED -> { }
    }
}

private void handleNo() {
    switch (currentStep) {
        case RING -> goToStep(QuestionStep.GILLS_WHEN_RING_NO);
        case FOREST_WHEN_RING_YES -> goToStep(QuestionStep.CONVEX_WHEN_RING_YES_NO_FOREST);
        case CONVEX_WHEN_RING_YES_NO_FOREST -> showMushroomResult("Coprin chevelu");
        case GILLS_WHEN_RING_NO -> showMushroomResult("Cepe de bordeaux");
        case CONVEX_WHEN_RING_NO_GILLS_YES -> showMushroomResult("Girolle");
        case NONE, FINISHED -> { }
    }
}

