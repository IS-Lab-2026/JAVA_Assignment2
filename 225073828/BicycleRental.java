    private void jToggleButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jToggleButton2ActionPerformed
  
      int startHour;
int endHour;

try {
    startHour = Integer.parseInt(start.getText().trim());
    endHour = Integer.parseInt(end.getText().trim());
} catch (NumberFormatException ex) {
    javax.swing.JOptionPane.showMessageDialog(
        this,
        "Please enter valid whole numbers (0–24) for start and end times."
    );
    return;
}

if (startHour < 0 || startHour >= 24 || endHour < 1 || endHour > 24 || startHour >= endHour) {
    javax.swing.JOptionPane.showMessageDialog(
        this,
        "Invalid time range. Start must be less than end, within 0 to 24."
    );
    return;
}

int totalCost = 0;

for (int hour = startHour; hour < endHour; hour++) {
    if ((hour >= 0 && hour < 7) || (hour >= 21 && hour < 24)) {
        // Off-peak / free hours: 0 RWF
    } else if ((hour >= 7 && hour < 14) || (hour >= 19 && hour < 21)) {
        totalCost += 1000;
    } else if (hour >= 14 && hour < 19) {
        totalCost += 1500;
    }
}

amount.setVisible(true);
amount.setText(totalCost + " RWF");
System.out.println("Your payment is: " + totalCost + " RWF");      // TODO add your handling code here:
    }//GEN-LAST:event_jToggleButton2ActionPerformed

