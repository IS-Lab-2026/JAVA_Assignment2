    private void BTNidentifyActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BTNidentifyActionPerformed
      if (!(gillsyes.isSelected() || gillsno.isSelected())
            || !(forestyes.isSelected() || forestno.isSelected())
            || !(ringyes.isSelected() || ringno.isSelected())
            || !(cupyes.isSelected() || cupno.isSelected())) {
        resultField.setText("Answer all questions");
        return;
    }

    boolean gills = gillsyes.isSelected();
    boolean forest = forestyes.isSelected();
    boolean ring = ringyes.isSelected();
    boolean cup = cupyes.isSelected();

    String result;

    if (!gills) {
        result = "Cepe de Bordeaux";
    } else if (!forest) {
        
        if (cup) {
            result = "Agaric Jaunissant";
        } else {
            result = "Coprin Chevelu";
        }
    } else {
        // Forest branch
        if (ring) {
            result = "Amanite Tue-Mouche";
        } else if (cup) {
            result = "Pied Bleu";
        } else {
            result = "Girolle";
        }
    }

    resultField.setText(result);// TODO add your handling code here:
    }//GEN-LAST:event_BTNidentifyActionPerformed

