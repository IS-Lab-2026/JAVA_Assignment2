    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
  // TODO add your handling code here:
  if(rdoyesring.isSelected()){
            if (Rdoyesforest.isSelected()){
                txtoutput.setText("Amanite tue-mouche");
            }
            else if(Rdonoforest.isSelected()){
                if(Rdoyescap.isSelected()){
                    txtoutput.setText("Agaric Jaunissant");
                }
                else if(Rdonocap.isSelected()){
                    txtoutput.setText("Coprin chevelu");
                }
                else{
                    txtoutput.setText("Invalid input");
                }
            }
            else{
               txtoutput.setText("Invalid input"); 
            }
        }
        else if(rdonoring.isSelected()){
            if(Rdoyesgills.isSelected()){
                if(Rdoyescap.isSelected()){
                    txtoutput.setText("Pied bleu");
                }
                else if(Rdonocap.isSelected()){
                   txtoutput.setText("Girolle"); 
                }
                else{
                  txtoutput.setText("Invalid input");
                }
        }
            else if(Rdonogills.isSelected()){
                txtoutput.setText("Cepe de bordeau");
            }
            else{
                txtoutput.setText("Invalid input");
            }
        }
        else{
          txtoutput.setText("Invalid input");  
        }
    }//GEN-LAST:event_jButton1ActionPerformed

