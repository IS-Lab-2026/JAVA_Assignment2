    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        
        int totalCost=0;
        int endT = Integer.parseInt(txtend.getText().trim());
        int startT = Integer.parseInt(txtstart.getText().trim());
        if (startT < 0 || startT > 23 || endT < 1 || endT > 24 || startT >= endT) {
            txttotalcost.setText("Invalid input.");
        } else {
            for (int hour = startT; hour < endT; hour++) {
                if (hour < 7 || hour >= 21) {
                    totalCost += 500;
                } else if ((hour >= 7 && hour < 14) || (hour >= 19 && hour < 21)) {
                    totalCost += 1000;
                } else {
                    totalCost += 1500;
                }
            }
            txttotalcost.setText ("Total rental cost: " + totalCost + " RWF ");

}// TODO add your handling code here:
    }//GEN-LAST:event_jButton1ActionPerformed

