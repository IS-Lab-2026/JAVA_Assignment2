    private void btnidentifyActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnidentifyActionPerformed
        String gills = radiogillsyes.isSelected() ? "yes" : (radiogillsno.isSelected() ? "no" : "");
    String forest = radioforestyes.isSelected() ? "yes" : (radioforestno.isSelected() ? "no" : "");
    String convexCup = radioconvexyes.isSelected() ? "yes" : (radioconvexno.isSelected() ? "no" : "");
    String ring = jRadioButton7.isSelected() ? "yes" : (jRadioButton8.isSelected() ? "no" : "");

    String mushroom;

    if (gills.equals("no")) {
        mushroom = "Cepe de Bordeaux";
    } else if (gills.equals("yes")) {
        if (forest.equals("no")) {
            if (convexCup.equals("yes")) {
                mushroom = "Agaric Jaunissant";
            } else if (convexCup.equals("no")) {
                mushroom = "Coprin chevelu";
            } else {
                txtresult.setText("Please select Yes or No for convex cup.");
                return;
            }
        } else if (forest.equals("yes")) {
            if (ring.equals("yes")) {
                mushroom = "Amanite tue-mouche";
            } else if (ring.equals("no")) {
                if (convexCup.equals("yes")) {
                    mushroom = "Pied bleu";
                } else if (convexCup.equals("no")) {
                    mushroom = "Girolle";
                } else {
                    txtresult.setText("Please select Yes or No for convex cup.");
                    return;
                }
            } else {
                txtresult.setText("Please select Yes or No for ring.");
                return;
            }
        } else {
            txtresult.setText("Please select Yes or No for forest.");
            return;
        }
    } else {
        txtresult.setText("Please select Yes or No for gills.");
        return;
    }

    txtresult.setText("Result: " + mushroom);
    

                                             

    }//GEN-LAST:event_btnidentifyActionPerformed

