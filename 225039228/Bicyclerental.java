    private void btncalculateamountActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btncalculateamountActionPerformed
        try {
        int starttime = Integer.parseInt(txtstart.getText().trim());
        int endtime = Integer.parseInt(txtend.getText().trim());

        if (starttime >= endtime) {
            txtresult.setText("Invalid time.");
            return;
        }

        int time = endtime - starttime;
        int totalCost;

        if (time < 5) {
            totalCost = time * 1500;
        } else if (time < 21) {
            totalCost = time * 1000;
        } else {
            totalCost = time * 500;
        }

        txtresult.setText("Total cost: " + totalCost);
    } catch (NumberFormatException ex) {
        txtresult.setText("Please enter valid numbers for start and end time.");
    

    }
    }//GEN-LAST:event_btncalculateamountActionPerformed

