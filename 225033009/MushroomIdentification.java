    private void btnexecuteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnexecuteActionPerformed
        TxtMushroomName.setText("");
        if (bgring.getSelection() == null || bgforest.getSelection() == null
                || bgconvex.getSelection() == null || bggills.getSelection() == null) {
            JOptionPane.showMessageDialog(this, "Please answer all four questions.");
            return;
        }
        boolean hasRing = rbtnringyes.isSelected();
        boolean inForest = rbtnforestyes.isSelected();
        boolean convexCap = rbtnconvexyes.isSelected();
        boolean hasGills = rbtngillsyes.isSelected();
        // Original classroom exercise rules only; not real-world identification.
        String result;
        if (hasRing && inForest && convexCap && hasGills) {
            result = "Amanita Mushroom";
        } else if (hasRing && !inForest && convexCap && hasGills) {
            result = "Button Mushroom (Champignon)";
        } else if (!hasRing && inForest && convexCap && hasGills) {
            result = "Chanterelle Mushroom";
        } else if (!hasRing && !inForest && !convexCap && hasGills) {
            result = "Oyster Mushroom";
        } else if (hasRing && inForest && !convexCap && !hasGills) {
            result = "Porcini Mushroom";
        } else {
            result = "Unknown Mushroom - Not Identified";
        }
        TxtMushroomName.setText(result);
    }//GEN-LAST:event_btnexecuteActionPerformed

