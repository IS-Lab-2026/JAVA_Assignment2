// Calculate rental cost
calculateButton.addActionListener(e -> {

    try {
        int startTime = Integer.parseInt(startField.getText().trim());
        int endTime = Integer.parseInt(endField.getText().trim());

        if (startTime < 0 || startTime > 23 ||
            endTime < 1 || endTime > 24 ||
            startTime >= endTime) {

            throw new IllegalArgumentException(
                "Invalid time!\n"
                + "Start time must be 0 to 23.\n"
                + "End time must be 1 to 24.\n"
                + "Start time must be less than end time."
            );
        }

        int total = 0;

        for (int hour = startTime; hour < endTime; hour++) {

            int rate;

            if (hour < 7) {
                rate = 500;
            } else if (hour < 14) {
                rate = 1000;
            } else if (hour < 19) {
                rate = 1500;
            } else if (hour < 21) {
                rate = 1000;
            } else {
                rate = 500;
            }

            total += rate;
        }

        amountField.setText(total + " RWF");

    } catch (NumberFormatException ex) {

        amountField.setText("");

        javax.swing.JOptionPane.showMessageDialog(
            frame,
            "Please enter valid numbers!",
            "Format Error",
            javax.swing.JOptionPane.ERROR_MESSAGE
        );

    } catch (IllegalArgumentException ex) {

        amountField.setText("");

        javax.swing.JOptionPane.showMessageDialog(
            frame,
            ex.getMessage(),
            "Input Error",
            javax.swing.JOptionPane.ERROR_MESSAGE
        );
    }
});

