    private void BtnactionActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtnactionActionPerformed
           if (Radiono1.isSelected()) {
            
            System.out.print("Does your mushroom have gills? (yes/no): ");
            
            if (Radioyes2.isSelected()) {
                txtmushroom.setText("Pied bleu");
            } else {
                txtmushroom.setText("Cepe de bordeaux");
            }
        } else if (Radioyes1.isSelected()) {
    
            System.out.print("Does your mushroom have a convex cup? (yes/no): ");
            
            if (Radiono2.isSelected()) {
                txtmushroom.setText("Coprin chevelu");
            } else {
              
                txtmushroom.setText("Does your mushroom grow in a forest? (yes/no): ");
                
                if (Radioyes3.isSelected()) {
                    txtmushroom.setText("Amanite tue-mouche");
                } else {
                    txtmushroom.setText("Agaric Jaunissant");
                }
            }
        } else {
            txtmushroom.setText("Invalid input");
        }    }//GEN-LAST:event_BtnactionActionPerformed

