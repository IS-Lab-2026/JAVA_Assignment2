    private void BtncalcActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtncalcActionPerformed
        // TODO add your handling code here:
        int startTime= Integer.parseInt(txtstart.getText().trim());
        int endTime =Integer.parseInt(txtend.getText().trim());
        int totalCost = 0;
        int rate;

        if (startTime < 0 || startTime > 23 ||
            endTime < 1 || endTime > 24 ||
            startTime >= endTime) {

            txtcost.setText("Invalid time entered.");
        } else {
            for (int hour = startTime; hour < endTime; hour++) {

                if (hour < 7 || hour >= 21) {
                    rate = 500;
                } else if (hour < 14) {
                    rate = 1000;
                } else if (hour < 19) {
                    rate = 1500;
                } else {
                    rate = 1000;
                }

                totalCost = totalCost + rate;
            }

            txtcost.setText(totalCost + " RWF");
        }
    }//GEN-LAST:event_BtncalcActionPerformed

