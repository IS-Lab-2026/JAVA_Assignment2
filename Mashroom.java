    private void btnNextActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnNextActionPerformed
        if (!rbYes.isSelected() && !rbNo.isSelected()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Please select Yes or No.");
            return;
        }
        boolean answer = rbYes.isSelected();
        rbYes.setSelected(false);
        rbNo.setSelected(false);

        switch (currentQuestion) {
            case CONVEX_CUP:
                convexCup = answer;
                if (answer) {
                    showQuestion(Question.RING);
                } else {
                    showQuestion(Question.GILLS);
                }
                break;
            case RING:
                hasRing = answer;
                if (!answer) {
                    showResult("Pied bleu");
                } else {
                    showQuestion(Question.FOREST);
                }
                break;
            case GILLS:
                hasGills = answer;
                if (!answer) {
                    showResult("Cepe de bordeaux");
                } else {
                    showQuestion(Question.FOREST);
                }
                break;
            case FOREST:
                if (convexCup) {
                    showResult(answer ? "Amanite tue-mouche" : "Agaric jaunissant");
                } else {
                    showResult(answer ? "Girolle" : "Coprin chevelu");
                }
                break;
        }
    }//GEN-LAST:event_btnNextActionPerformed

    private void showQuestion(Question question) {
        currentQuestion = question;
        switch (question) {
            case CONVEX_CUP:
                lblQuestion.setText("Does your mushroom have a convex cup?");
                break;
            case RING:
                lblQuestion.setText("Does your mushroom have a ring?");
                break;
            case GILLS:
                lblQuestion.setText("Does your mushroom have gills?");
                break;
            case FOREST:
                lblQuestion.setText("Does your mushroom grow in a forest?");
                break;
        }
        jLabel1.setText("Question " + questionNumber(question) + " of 3");
        btnNext.setText("Next");
    }

    private int questionNumber(Question question) {
        if (question == Question.CONVEX_CUP) return 1;
        if (question == Question.RING || question == Question.GILLS) return 2;
        return 3;
    }

    private void showResult(String mushroom) {
        lblQuestion.setText("Mushroom identified:");
        jLabel1.setText(mushroom);
        btnNext.setEnabled(false);
        rbYes.setEnabled(false);
        rbNo.setEnabled(false);
    }

    private void resetGame() {
        convexCup = null;
        hasRing = null;
        hasGills = null;
        btnNext.setEnabled(true);
        rbYes.setEnabled(true);
        rbNo.setEnabled(true);
        rbYes.setSelected(false);
        rbNo.setSelected(false);
        showQuestion(Question.CONVEX_CUP);
    }

