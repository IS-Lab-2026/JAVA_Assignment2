    private void forestBoxActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_forestBoxActionPerformed
        int forest = forestBox.getSelectedIndex(); // 0 = No, 1 = Yes
    
        if (forest == 1) {
            // It is a forest mushroom, so the 3rd question must be about the Ring
            dynamicLabel.setText("Has Ring?");
       } else {
            // It is a meadow mushroom, so the 3rd question must be about the Gills
            dynamicLabel.setText("Has Gills?");
       }
    }//GEN-LAST:event_forestBoxActionPerformed

    private void checkButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_checkButtonActionPerformed
                                            
    // getSelectedIndex() returns 0 for "No", 1 for "Yes"
    int forest = forestBox.getSelectedIndex(); // 0 = No, 1 = Yes
    int cup = cupBox.getSelectedIndex();
    int dynamicChoice = dynamicBox.getSelectedIndex(); // Serves as Ring OR Gills

    String type = "";

    if (forest == 0) {
        // Meadow branch (3rd question was Gills, but it doesn't matter for the final classification)
        if (cup == 1) {
            type = "Agaric Jaunissant";
        } else {
            type = "Coprin Chevelu";
        }
    } else {
        // Forest branch
        if (cup == 1) {
            // 3rd question was "Has Ring?"
            if (dynamicChoice == 1) {
                type = "Amanite Tue-mouche";
            } else {
                type = "Pied Bleu";
            }
        } else {
            // 3rd question was "Has Gills?"
            if (dynamicChoice == 1) {
                type = "Girolle";
            } else {
                type = "Cepe de Bordeaux";
            }
        }
    }

    mushroomResultLabel.setText("Mushroom Identity: " + type);
    }//GEN-LAST:event_checkButtonActionPerformed

