    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        int forest = forestBox.getSelectedIndex();
    int cup = cupBox.getSelectedIndex();
    String identity = mushroomResultLabel.getText().replace("Mushroom Identity: ", "").trim();

    if (identity.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this, "Please run classification logic first!");
        return;
    }

    String env = (forest == 1) ? "Forest" : "Meadow";
    String capShape = (cup == 1) ? "Convex" : "Other";

    // Append a clean structured data row with cell padding boundaries
    tableHtmlBody += "<tr style='background-color:#F2F2F2; color:#333333;'>"
                  + "  <td align='left'><b>" + currentUserName + "</b></td>"
                  + "  <td align='left'>" + env + "</td>"
                  + "  <td align='left'>" + capShape + "</td>"
                  + "  <td align='left' style='color:#D24726; font-weight:bold;'>" + identity + "</td>"
                  + "</tr>";

    // Re-render the complete active dataset with structural bounds
    mushroomHistoryArea.setText(tableHtmlBody + "</table>");
    }//GEN-LAST:event_jButton2ActionPerformed


