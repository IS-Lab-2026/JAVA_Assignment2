    private void calculateButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_calculateButtonActionPerformed
                                                
    try {
        int startHour = Integer.parseInt(startField.getText().trim());
        int endHour = Integer.parseInt(endField.getText().trim());

        // Simple input validation check
        if (startHour < 0 || endHour > 24 || startHour >= endHour) {
            resultLabel.setText("Invalid input");
            return;
        }

        int total = 0;
        int hour = startHour;
        int rent;

        // Execute your pricing math loops
        while (hour < endHour) {
            if (hour < 7 || hour >= 21) {
                rent = 500;
            } else if (hour < 14 || hour >= 19) {
                rent = 1000;
            } else {
                rent = 1500;
            }
            total = total + rent;
            hour = hour + 1;
        }

        resultLabel.setText(total + " RWF");

    } catch (NumberFormatException e) {
        resultLabel.setText("Please enter valid numbers");
    }

    }//GEN-LAST:event_calculateButtonActionPerformed

    private void saveButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_saveButtonActionPerformed
         String start = startField.getText().trim();
    String end = endField.getText().trim();
    String result = resultLabel.getText().replace("Total to pay: ", "").trim();

    if (start.isEmpty() || end.isEmpty() || result.contains("Invalid") || result.contains("valid")) {
        javax.swing.JOptionPane.showMessageDialog(this, "Nothing valid to save yet!");
        return;
    }

    // Append a distinct, cleanly separated data row with alternating row background coloring
    tableHtmlBody += "<tr style='background-color:#F2F2F2; color:#333333;'>"
                  + "  <td align='left'><b>" + currentUserName + "</b></td>"
                  + "  <td align='center'>" + start + "h</td>"
                  + "  <td align='center'>" + end + "h</td>"
                  + "  <td align='right' style='color:#2B579A; font-weight:bold;'>" + result + "</td>"
                  + "</tr>";

    // Close the table out and push it directly into the JTextPane viewport display window
    historyarea.setText(tableHtmlBody + "</table>");
    }//GEN-LAST:event_saveButtonActionPerformed

